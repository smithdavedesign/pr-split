// Runs git, always with an argv array (never a shell). Apart from execute.js, which runs the
// generated script, this is the only module that starts processes.
import { execFile } from 'node:child_process';
import { appendFileSync, existsSync, mkdirSync, readFileSync, realpathSync } from 'node:fs';
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { promisify } from 'node:util';
import { usageError } from './errors.js';

const execFileAsync = promisify(execFile);
const MAX_OUTPUT_BYTES = 64 * 1024 * 1024;

/**
 * @typedef {'A' | 'M' | 'D' | 'R' | 'C' | 'T'} ChangeStatus
 * @typedef {{ path: string, status: ChangeStatus, oldPath?: string,
 *             additions: number, deletions: number, binary: boolean }} ChangedFile
 */

export async function git(args, cwd) {
  try {
    const { stdout } = await execFileAsync('git', args, { cwd, encoding: 'utf8', maxBuffer: MAX_OUTPUT_BYTES });
    return stdout;
  } catch (err) {
    if (err.code === 'ENOENT') throw new Error('git is not installed or not on PATH');
    // `git push` starts with "To <url>"; the line that says why is further down.
    const output = String(err.stderr || err.message).trim().split('\n');
    const detail =
      output.find((line) => /\[(remote )?rejected\]/.test(line)) ??
      output.find((line) => /^(error|fatal):/.test(line.trim())) ??
      output[0];
    throw new Error(`git ${args[0]} failed: ${detail.trim()}`);
  }
}

/** Parses `git diff --name-status -z` output. */
export function parseNameStatus(output) {
  const tokens = output.split('\0');
  const files = [];
  for (let i = 0; i < tokens.length && tokens[i] !== ''; ) {
    const status = tokens[i++][0];
    if (status === 'R' || status === 'C') {
      const oldPath = tokens[i++];
      files.push({ status, path: tokens[i++], oldPath });
    } else {
      files.push({ status, path: tokens[i++] });
    }
  }
  return files;
}

/** Parses `git diff --numstat -z` output into path → line counts (binary files count as 0 lines). */
export function parseNumstat(output) {
  const tokens = output.split('\0');
  const stats = new Map();
  for (let i = 0; i < tokens.length && tokens[i] !== ''; i++) {
    const match = /^(-|\d+)\t(-|\d+)\t(.*)$/s.exec(tokens[i]);
    if (!match) continue;
    let path = match[3];
    if (path === '') {
      // Renames and copies: "<added>\t<deleted>\t\0<old path>\0<new path>\0"
      i += 2;
      path = tokens[i];
    }
    const binary = match[1] === '-';
    stats.set(path, {
      additions: binary ? 0 : Number(match[1]),
      deletions: binary ? 0 : Number(match[2]),
      binary,
    });
  }
  return stats;
}

function assertRef(ref, label) {
  if (typeof ref !== 'string' || ref === '' || ref.startsWith('-')) {
    throw usageError(`invalid ${label} ref ${JSON.stringify(ref)}`);
  }
}

async function resolveCommit(ref, label, cwd) {
  try {
    return (await git(['rev-parse', '--verify', '--quiet', `${ref}^{commit}`], cwd)).trim();
  } catch {
    throw new Error(`unknown ${label} "${ref}" (no such branch or commit)`);
  }
}

/**
 * Keeps the generated script out of `git add -A` by listing it in the repo's own, unshared
 * .git/info/exclude, unless it's outside the work tree, already ignored or tracked.
 * Paths with characters that are special in ignore patterns are left alone.
 * @returns {Promise<boolean>} whether a pattern was added
 */
export async function excludeLocally({ root, file }) {
  // The top level git reports has symlinks resolved (macOS: /tmp → /private/tmp), so resolve the file's too.
  const real = join(realpathSync(dirname(file)), basename(file));
  const rel = relative(root, real).split(sep).join('/');
  if (rel === '' || rel === '..' || rel.startsWith('../') || isAbsolute(rel) || !/^[\w./-]+$/.test(rel)) return false;
  const succeeds = (args) => git(args, root).then(() => true, () => false);
  if (await succeeds(['check-ignore', '-q', '--', rel])) return false;
  if (await succeeds(['ls-files', '--error-unmatch', '--', rel])) return false;
  try {
    const exclude = resolve(root, (await git(['rev-parse', '--git-path', 'info/exclude'], root)).trim());
    mkdirSync(dirname(exclude), { recursive: true });
    const current = existsSync(exclude) ? readFileSync(exclude, 'utf8') : '';
    const separator = current === '' || current.endsWith('\n') ? '' : '\n';
    appendFileSync(exclude, `${separator}# generated by pr-split\n/${rel}\n`);
    return true;
  } catch {
    return false; // a convenience only: a read-only .git must not stop the split
  }
}

/** Checks that `remote` is a configured git remote, before anything is built for `--push`. */
export async function assertRemote({ cwd, remote }) {
  if (typeof remote !== 'string' || !/^[^\s\u0000-\u001f\u007f-][^\s\u0000-\u001f\u007f]*$/.test(remote)) {
    throw usageError(`invalid --remote ${JSON.stringify(remote)}`);
  }
  try {
    await git(['remote', 'get-url', remote], cwd);
  } catch {
    throw usageError(`no git remote named "${remote}" (see git remote -v, or pass --remote <name>)`);
  }
}

export async function repoRoot(cwd) {
  try {
    return (await git(['rev-parse', '--show-toplevel'], cwd)).trim();
  } catch (err) {
    if (/not installed/.test(err.message)) throw err;
    throw new Error('not inside a git repository');
  }
}

/**
 * The branch, remote-tracking branch or tag name `ref` stands for ("HEAD" gives the checked-out
 * branch), or null for anything else, like a SHA or "HEAD~1". The generated script switches
 * branches, so only names like these mean the same thing from start to finish.
 */
async function stableName(ref, cwd) {
  const full = (await git(['rev-parse', '--verify', '--quiet', '--symbolic-full-name', ref], cwd).catch(() => '')).trim();
  return /^refs\/(?:heads|remotes|tags)\/(.+)$/.exec(full)?.[1] ?? null;
}

/**
 * Files changed on `feature` since it branched from `base` (the three-dot diff), sorted by path.
 * `baseRef` and `featureRef` are stable names for the script: the branch or tag name, else the SHA.
 * @returns {Promise<{ baseRef: string, featureRef: string, mergeBase: string, featureSha: string, files: ChangedFile[] }>}
 */
export async function getChanges({ cwd, base, feature }) {
  assertRef(base, 'base');
  assertRef(feature, 'feature');
  const baseSha = await resolveCommit(base, 'base', cwd);
  const featureSha = await resolveCommit(feature, 'feature', cwd);
  const baseRef = (await stableName(base, cwd)) ?? baseSha;
  const featureRef = (await stableName(feature, cwd)) ?? featureSha;
  let mergeBase;
  try {
    mergeBase = (await git(['merge-base', baseSha, featureSha], cwd)).trim();
  } catch {
    // CI checkouts are shallow by default, which hides the commit both branches share.
    const shallow = (await git(['rev-parse', '--is-shallow-repository'], cwd).catch(() => '')).trim() === 'true';
    const hint = shallow ? ' in this shallow clone; fetch the full history (git fetch --unshallow, or fetch-depth: 0 in actions/checkout)' : '';
    throw new Error(`"${feature}" and "${base}" have no common history${hint}`);
  }
  const files = await diffFiles(cwd, mergeBase, featureSha);
  return { baseRef, featureRef, mergeBase, featureSha, files };
}

/** Files changed from commit `from` to commit `to`, with line counts, sorted by path. */
async function diffFiles(cwd, from, to) {
  const diff = ['diff', '-z', '-M', '--no-color', '--no-ext-diff', '--no-relative'];
  const [nameStatus, numstat] = await Promise.all([
    git([...diff, '--name-status', from, to], cwd),
    git([...diff, '--numstat', from, to], cwd),
  ]);
  const stats = parseNumstat(numstat);
  const files = parseNameStatus(nameStatus).map((file) => ({
    ...file,
    ...(stats.get(file.path) ?? { additions: 0, deletions: 0, binary: false }),
  }));
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return files;
}

const lines = (text) => text.split('\n').filter((line) => line !== '');

/** The name `ref` stands for, as the script names it: a branch or tag name, else the commit SHA. */
export async function refName({ cwd, ref, label = 'feature' }) {
  assertRef(ref, label);
  const sha = await resolveCommit(ref, label, cwd);
  return (await stableName(ref, cwd)) ?? sha;
}

/**
 * The branch on GitHub a PR can target for `ref`: a local branch's name, or a remote-tracking
 * branch's name without its remote ("origin/main" → "main"). Null for tags, SHAs and the like.
 */
export async function branchName({ cwd, ref }) {
  const full = (await git(['rev-parse', '--verify', '--quiet', '--symbolic-full-name', ref], cwd).catch(() => '')).trim();
  const local = /^refs\/heads\/(.+)$/.exec(full);
  if (local) return local[1];
  const tracking = /^refs\/remotes\/(.+)$/.exec(full)?.[1];
  if (!tracking) return null;
  // Remote names may contain "/", so match the longest one.
  const remote = lines(await git(['remote'], cwd))
    .filter((name) => tracking.startsWith(`${name}/`))
    .sort((a, b) => b.length - a.length)[0];
  const name = remote ? tracking.slice(remote.length + 1) : null;
  return name && name !== 'HEAD' ? name : null;
}

/** The "Part i/n of <feature>, split by pr-split." line of a layer's commit (see plan.commitMessage). */
const PART = /^Part (\d+)\/(\d+) of (.*), split by pr-split\.$/m;

async function readCommit(cwd, branch) {
  try {
    const out = await git(['log', '-1', '--format=%H%x00%P%x00%B', `refs/heads/${branch}`, '--'], cwd);
    const [sha, parents, message] = out.split('\0');
    return { sha, parents: parents.split(' ').filter(Boolean), message: message.trimEnd() };
  } catch {
    return null;
  }
}

function partOf(message, feature) {
  const match = PART.exec(message);
  return match && match[3] === feature ? { index: Number(match[1]), count: Number(match[2]) } : null;
}

/**
 * @typedef {{ index: number, name: string, summary: string, title: string, branch: string,
 *   parent: string, sha: string, refs: string[], files: ChangedFile[],
 *   additions: number, deletions: number }} StackLayer
 */

/**
 * Reads the stack pr-split built for `feature` from the branches themselves (bottom first): each
 * must be pr-split's single commit for that layer, on top of the branch before it. `base` is what
 * the bottom layer's PR targets. The PRs say what the branches hold, whatever produced them.
 * @returns {Promise<StackLayer[]>}
 */
export async function readStack({ cwd, feature, base, branches }) {
  const layers = [];
  for (const [i, branch] of branches.entries()) {
    const commit = await readCommit(cwd, branch);
    if (!commit) throw new Error(`${branch} doesn't exist; build the stack with pr-split --execute first`);
    const part = partOf(commit.message, feature);
    if (!part || part.index !== i + 1 || part.count !== branches.length) {
      throw new Error(`${branch} isn't layer ${i + 1} of ${branches.length} that pr-split built for ${feature}; rebuild the stack with pr-split --execute`);
    }
    if (commit.parents.length !== 1 || (i > 0 && commit.parents[0] !== layers[i - 1].sha)) {
      throw new Error(`${branch} isn't a single commit on top of ${i > 0 ? branches[i - 1] : base}; rebuild the stack with pr-split --execute`);
    }
    const files = await diffFiles(cwd, commit.parents[0], commit.sha);
    const title = commit.message.split('\n')[0];
    layers.push({
      index: i + 1,
      name: branch.replace(/^.*\/\d+-/, ''),
      summary: title.replace(/^[a-z]+(\([^)]*\))?!?: /, ''),
      title,
      branch,
      parent: i === 0 ? base : branches[i - 1],
      sha: commit.sha,
      refs: [...commit.message.matchAll(/^Refs: (.+)$/gm)].map((m) => m[1]),
      files,
      additions: files.reduce((sum, f) => sum + f.additions, 0),
      deletions: files.reduce((sum, f) => sum + f.deletions, 0),
    });
  }
  return layers;
}

/**
 * Finds the stack pr-split built for `feature` among the local `<prefix>/*` branches, for
 * --pr-only: the one complete chain of its layer commits, layer 1 up to layer n.
 * @returns {Promise<string[]>} the branch names, bottom first
 */
export async function findStack({ cwd, feature, prefix }) {
  const names = lines(await git(['for-each-ref', '--format=%(refname:lstrip=2)', `refs/heads/${prefix}/`], cwd));
  const layers = [];
  for (const branch of names) {
    if (branch.startsWith(`${prefix}/tmp/`)) continue;
    const commit = await readCommit(cwd, branch);
    const part = commit && partOf(commit.message, feature);
    if (part) layers.push({ branch, ...commit, ...part });
  }
  const chains = [];
  for (const top of layers.filter((l) => l.index === l.count)) {
    const chain = [top];
    while (chain[0].index > 1) {
      const below = layers.find(
        (l) => l.index === chain[0].index - 1 && l.count === top.count && l.sha === chain[0].parents[0],
      );
      if (!below) break;
      chain.unshift(below);
    }
    if (chain[0].index === 1) chains.push(chain.map((l) => l.branch));
  }
  if (chains.length === 1) return chains[0];
  if (chains.length > 1) {
    throw new Error(
      `found ${chains.length} stacks that pr-split built for ${feature} (topped by ${chains.map((c) => c.at(-1)).join(', ')}); ` +
        'delete the branches of the old ones (git branch -D …) and try again',
    );
  }
  if (layers.length > 0) {
    throw new Error(
      `pr-split's branches for ${feature} don't form a complete stack (a layer is missing or has commits pr-split didn't make); rebuild it with pr-split --execute`,
    );
  }
  throw new Error(`no stack that pr-split built for ${feature} was found; build one with pr-split --execute (or --execute --pr)`);
}

/**
 * Pushes the stack for --pr-only: one all-or-nothing push, upstreams set. A stack rebuilt since
 * the last push needs the force, but --pr-only rebuilds nothing, so it also refuses to drop a
 * commit someone pushed to a layer branch that was fetched but isn't in the local branch
 * (--force-if-includes, git 2.30+).
 */
export async function pushBranches({ cwd, remote, branches }) {
  await git(['push', '--atomic', '--force-with-lease', '--force-if-includes', '-u', remote, ...branches], cwd);
}
